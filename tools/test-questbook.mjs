import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
/* global document, getComputedStyle, innerWidth, innerHeight */
const [base, playwrightModule, screenshots] = process.argv.slice(2);
if (!playwrightModule) throw new Error('Usage: node tools/test-questbook.mjs <app-url> <playwright-module> [screenshots]');
const { chromium } = await import(playwrightModule);
const browser = await chromium.launch();
if (screenshots) await mkdir(screenshots, { recursive: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' });
  const page = await context.newPage();
  const errors = [], questRequests = [], failures = [];
  page.on('pageerror', error => errors.push(error.message));
  context.on('request', request => { if (/\/quests\/(?:versions\.json|[a-f0-9]{64}\.mpk)$/.test(new URL(request.url()).pathname)) questRequests.push(request.url()); });
  context.on('requestfailed', request => { if (new URL(request.url()).pathname.endsWith('.mpk')) failures.push(request.url()); });
  let release;
  const gate = new Promise(resolve => release = resolve);
  await context.route('**/quests/*.mpk', async route => { await gate; await route.continue(); });
  await page.goto(base, { waitUntil: 'domcontentloaded', timeout: 120000 });
  await page.getByRole('link', { name: 'Open item catalogue', exact: true }).click();
  await page.locator('.item-tile').first().waitFor({ timeout: 120000 });
  assert.equal(questRequests.length, 0, 'Recipe browsing does not fetch quest data or its version index');
  const finderLink = page.getByRole('link', { name: 'Recipe Finder', exact: true });
  const finderWidth = (await finderLink.boundingBox()).width;
  await finderLink.click();
  await page.waitForURL(url => url.searchParams.get('page') === 'finder');
  assert.equal((await finderLink.boundingBox()).width, finderWidth, 'Acknowledging the finder blip preserves button width');
  const questLink = page.getByRole('link', { name: 'Questbook Browser', exact: true });
  const questWidth = (await questLink.boundingBox()).width;
  await questLink.click();
  await page.getByRole('progressbar', { name: 'Questbook loading' }).waitFor();
  await page.getByRole('link', { name: 'Items', exact: true }).click();
  await questLink.click();
  await page.getByRole('progressbar', { name: 'Questbook loading' }).waitFor();
  release();
  await page.locator('.quest-node').first().waitFor({ timeout: 60000 });
  assert.equal((await questLink.boundingBox()).width, questWidth, 'Acknowledging the questbook blip preserves button width');
  assert.equal(questRequests.filter(url => url.endsWith('.mpk')).length, 1, 'Navigating away does not restart a quest download');
  assert.deepEqual(failures, []);
  assert.equal(await page.locator('.quest-total').innerText(), '3,814 Quests');
  assert.equal(await page.locator('.quest-chapter').count(), 46);
  assert.equal(await page.getByRole('button', { name: 'Chapters', exact: true }).isVisible(), false);
  assert.equal(await page.locator('.quest-toolbar').count(), 0, 'No redundant quest toolbar consumes vertical space');
  assert.equal(await page.locator('.primary-nav select[aria-label="Questbook version"]').count(), 1, 'Version picker is integrated in main navigation');
  assert(await page.locator('.quest-version-control label').getByText('Quest version', { exact:true }).isVisible(), 'Quest version has a visible label');
  assert(await page.locator('.chapter-title').evaluate(node => node.querySelector('small').getBoundingClientRect().left - node.querySelector('h1').getBoundingClientRect().right < 24), 'Chapter count sits next to its title');
  const node = page.locator('.quest-node').first();
  await node.hover();
  const tooltip = page.locator('.quest-tooltip');
  await tooltip.waitFor();
  assert.match(await tooltip.innerText(), /Requires: \((?:AND|OR|XOR|NAND|NOR|XNOR)\)/);
  assert.doesNotMatch(await tooltip.innerText(), /Tasks Complete|\d+\s*\/\s*\d+/i);
  assert(await tooltip.locator('.requirements').evaluate(node => getComputedStyle(node).color === 'rgb(170, 170, 170)' && getComputedStyle(node.querySelector('.logic')).color === 'rgb(0, 0, 255)' && getComputedStyle(node).textDecorationLine === 'none'), 'Requires stays gray; operator uses the native quest-detail highlight');
  const map = page.locator('.quest-world');
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  const zoomed = await map.getAttribute('style');
  await node.click();
  await page.locator('.quest-detail').waitFor();
  assert.equal(await page.locator('.quest-title h1').textContent(), (await page.locator('.quest-title h1').textContent()).trim(), 'Title renderer adds no leading or trailing spaces');
  assert.equal(await page.locator('.quest-description .quest-requirements').count(), 0, 'Quest prerequisites stay out of the description panel');
  const rewardRow = page.locator('.quest-rewards .special-good-cell').first();
  await rewardRow.waitFor();
  assert.equal(await rewardRow.evaluate(node => getComputedStyle(node).flexDirection), 'row');
  assert(await rewardRow.locator('.special-good-label').isVisible(), 'Item names remain visible beside their slots');
  assert.equal(await page.locator('.quest-chapters').count(), 0, 'Quest details replace the whole chapter view');
  assert.equal(await page.getByRole('button', { name: /^(Detect|Submit|Claim)/i }).count(), 0);
  const checkbox = page.locator('[data-section-type="checkbox"] img');
  await checkbox.waitFor();
  await checkbox.evaluate(image => image.decode());
  assert(await checkbox.evaluate(image => image.complete && image.naturalWidth === 16), 'Checkbox uses the native mod icon');
  if (screenshots) await page.screenshot({ path: `${screenshots}/quest-details-desktop.png` });
  await page.locator('.quest-back').click();
  await node.waitFor();
  assert.equal(await map.getAttribute('style'), zoomed, 'Back preserves the chapter camera');
  const search = page.getByRole('textbox', { name: 'Search all quests', exact: true }).filter({ visible: true });
  await search.fill('wheat');
  await page.locator('.quest-search-result').first().waitFor();
  assert.equal(await page.locator('.quest-chapter').count(), 46, 'Search preserves the chapter sidebar');
  assert((await page.locator('.quest-search-result small').first().innerText()).length > 0, 'Results include their chapter');
  await search.fill('');
  await page.getByRole('button', { name: 'Fit', exact: true }).click();
  await page.mouse.move(1400, 980);
  if (screenshots) await page.screenshot({ path: `${screenshots}/quest-map-desktop.png` });
  await page.reload();
  await page.locator('.quest-node').first().waitFor({ timeout: 60000 });
  assert.equal(questRequests.filter(url => url.endsWith('.mpk')).length, 1, 'Reload reads the verified quest pack from local storage');
  const detailUrl = new URL(page.url());
  detailUrl.searchParams.set('quest', '00000000-0000-0000-0000-00000000000a');
  await page.goto(detailUrl.href);
  const desktopDescription = page.getByRole('region', { name: 'Quest description', exact: true });
  await desktopDescription.waitFor();
  const shortHeight = await desktopDescription.evaluate(node => node.clientHeight);
  assert(await desktopDescription.evaluate(node => node.scrollHeight === node.clientHeight), 'Short descriptions fit their content without unnecessary scrolling');
  assert(await page.locator('.task-logic').evaluate(node => {
    const style = getComputedStyle(node), heading = getComputedStyle(node.parentElement);
    return style.display === 'inline' && style.fontFamily === heading.fontFamily && style.fontSize === heading.fontSize && style.color !== heading.color;
  }), 'Task logic stays inline with matching Minecraft font size and a muted color');
  detailUrl.searchParams.set('quest', '00000000-0000-0000-0000-000000000b0f');
  await page.goto(detailUrl.href);
  await desktopDescription.waitFor();
  assert(await desktopDescription.evaluate(node => node.clientHeight <= node.parentElement.clientHeight * .4 + 1 && node.scrollHeight > node.clientHeight), 'Long desktop descriptions scroll at the reduced height cap');
  assert(shortHeight < await desktopDescription.evaluate(node => node.clientHeight), 'Short descriptions leave more room for rewards');
  assert.deepEqual(errors, []);

  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, serviceWorkers: 'block' });
  const mobile = await phone.newPage();
  const mobileErrors = [];
  mobile.on('pageerror', error => mobileErrors.push(error.message));
  const url = new URL(base); url.searchParams.set('page', 'quests');
  await mobile.goto(url.href);
  await mobile.locator('.quest-node').first().waitFor({ timeout: 120000 });
  assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Phone layout fits the viewport');
  assert(await mobile.locator('.primary-nav').evaluate(node => node.scrollWidth <= node.clientWidth), 'Phone navigation and quest version fit without horizontal scrolling');
  const mobileNode = mobile.locator('.quest-node').first();
  const originalUrl = mobile.url();
  await mobileNode.tap();
  await mobile.locator('.touch-tooltip .quest-tooltip').waitFor();
  assert.equal(mobile.url(), originalUrl, 'First touch previews without navigation');
  if (screenshots) await mobile.screenshot({ path: `${screenshots}/quest-preview-mobile.png` });
  await mobileNode.tap();
  await mobile.locator('.quest-detail').waitFor();
  assert(await mobile.locator('.quest-title .quest-icon').isVisible(), 'Phone quest title keeps its item icon');
  assert.equal(await mobile.locator('.quest-back svg').count(), 1, 'Back uses the shared scaled arrow');
  assert.equal(await mobile.locator('.quest-back span').isVisible(), false, 'Phone back button is icon-only');
  const swipeTitle = mobile.locator('.quest-title h1');
  await swipeTitle.dispatchEvent('pointerdown', {pointerType:'touch',pointerId:41,isPrimary:true,clientX:100,clientY:180});
  await swipeTitle.dispatchEvent('pointermove', {pointerType:'touch',pointerId:41,isPrimary:true,clientX:105,clientY:260});
  await swipeTitle.dispatchEvent('pointerup', {pointerType:'touch',pointerId:41,isPrimary:true,clientX:105,clientY:260});
  assert(await mobile.locator('.quest-detail').isVisible(), 'Vertical movement does not navigate back');
  await swipeTitle.dispatchEvent('pointerdown', {pointerType:'touch',pointerId:42,isPrimary:true,clientX:100,clientY:180});
  await swipeTitle.dispatchEvent('pointermove', {pointerType:'touch',pointerId:42,isPrimary:true,clientX:240,clientY:184});
  await swipeTitle.dispatchEvent('pointerup', {pointerType:'touch',pointerId:42,isPrimary:true,clientX:240,clientY:184});
  await mobile.locator('.quest-node').first().waitFor();
  assert.equal(new URL(mobile.url()).searchParams.get('quest'), null, 'Right swipe returns to the chapter');
  await mobile.goForward();
  await mobile.locator('.quest-detail').waitFor();
  assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const longQuestUrl = new URL(mobile.url());
  longQuestUrl.searchParams.set('quest', '00000000-0000-0000-0000-000000000b0f');
  await mobile.goto(longQuestUrl.href);
  const description = mobile.getByRole('region', { name: 'Quest description', exact: true });
  await description.waitFor();
  assert(await description.evaluate(node => node.scrollHeight > node.clientHeight), 'Long quest text overflows its own bounded phone panel');
  assert(await description.evaluate(node => node.clientHeight <= innerHeight * .4 + 1), 'Phone descriptions use the reduced height cap');
  const detailScroll = await mobile.locator('.quest-detail-columns').evaluate(node => node.scrollTop);
  await description.evaluate(node => { node.scrollTop = 150; });
  assert(await description.evaluate(node => node.scrollTop > 0), 'Quest text can scroll independently');
  assert.equal(await mobile.locator('.quest-detail-columns').evaluate(node => node.scrollTop), detailScroll, 'Scrolling text preserves the surrounding detail position');
  if (screenshots) await mobile.screenshot({ path: `${screenshots}/quest-description-mobile.png` });
  await mobile.locator('.quest-back').tap();
  await mobileNode.waitFor();
  await mobile.getByRole('button', { name: 'Chapters', exact: true }).tap();
  await mobile.locator('.quest-chapters.mobile-open').waitFor();
  await mobile.locator('.quest-chapter').nth(2).tap();
  await mobile.locator('.quest-chapters.mobile-open').waitFor({ state: 'hidden' });
  await mobile.getByRole('textbox', { name: 'Search all quests', exact: true }).filter({ visible: true }).fill('iron ingot');
  await mobile.locator('.quest-search-result').first().waitFor();
  assert.equal(await mobile.locator('.quest-chapters.mobile-open').count(), 0, 'Mobile search is available outside the chapter drawer');
  assert(await mobile.locator('.quest-search-result').first().evaluate(node => getComputedStyle(node).minWidth === '0px'));
  if (screenshots) await mobile.screenshot({ path: `${screenshots}/quest-search-mobile.png` });
  const locationUrl = new URL(mobile.url());
  locationUrl.searchParams.set('quest', '00000000-0000-0000-0000-00000000096c');
  await mobile.goto(locationUrl.href);
  const locationMap = mobile.getByRole('img', { name: 'Location map', exact: true });
  await locationMap.waitFor();
  const mapBox = await locationMap.boundingBox();
  assert.equal(mapBox.width, 48); assert.equal(mapBox.height, 48);
  assert.equal(await locationMap.locator('.unknown').innerText(), '?', 'Location cue uses the native unknown-position marker without inventing player coordinates');
  assert.deepEqual(mobileErrors, []);
  console.log('Quest-only lazy download/cache, navigation during loading, stable blip widths, native layouts, tooltips, zoom/back, search, mobile preview/open and chapter drawer passed.');
} finally { await browser.close(); }
